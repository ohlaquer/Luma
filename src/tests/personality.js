function computeScale(answers, { plus, minus, coef }) {
    let raw = 0;
    for (let i = 0; i < answers.length; i++) {
        const idx = i + 1; // питання 1..88
        const a = answers[i] === 1 ? 1 : 0; // 1=Так, 0=Ні
        if (plus.has(idx)) raw += a;         // «Так» по плюсовому ключу
        if (minus.has(idx)) raw += (1 - a);  // «Ні» по мінусовому ключу
    }
    return { raw, score: raw * coef };
}

